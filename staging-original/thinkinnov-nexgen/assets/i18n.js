function getPreferredLanguage() {
  const stored = localStorage.getItem("site-lang");
  if (stored === "jp" || stored === "en") return stored;
  return navigator.language.toLowerCase().startsWith("ja") ? "jp" : "en";
}

function translateTextNodes(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach((node) => {
    const raw = node.nodeValue;
    const trimmed = raw.trim();
    if (!trimmed || !jpText[trimmed]) return;
    node.nodeValue = raw.replace(trimmed, jpText[trimmed]);
  });
}

function applyPreferredLanguage() {
  const lang = getPreferredLanguage();
  document.documentElement.lang = lang === "jp" ? "ja" : "en";
  document.querySelectorAll(".lang-toggle").forEach((button) => {
    button.textContent = lang === "jp" ? "JP / EN" : "EN / JP";
    button.classList.toggle("is-jp", lang === "jp");
  });
  if (lang === "jp") translateTextNodes(document.body);
  if (lang === "jp") {
    document.querySelectorAll("input[placeholder], textarea[placeholder]").forEach((field) => {
      field.placeholder = jpText[field.placeholder] || field.placeholder;
    });
    document.querySelectorAll("option").forEach((option) => {
      option.textContent = jpText[option.textContent.trim()] || option.textContent;
    });
  }
}

window.applyPreferredLanguage = applyPreferredLanguage;
window.getPreferredLanguage = getPreferredLanguage;

document.addEventListener("click", (event) => {
  const button = event.target.closest(".lang-toggle");
  if (!button) return;
  const next = getPreferredLanguage() === "jp" ? "en" : "jp";
  localStorage.setItem("site-lang", next);
  window.location.reload();
});

document.addEventListener("DOMContentLoaded", applyPreferredLanguage);
