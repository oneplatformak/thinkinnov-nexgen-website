const jaQuotes = require("../i18n/ja-testimonials");

function phpArray(values) {
  return "[" + values.map((v) => `'${String(v).replace(/[\\']/g, "\\$&")}'`).join(", ") + "]";
}

function phpMap(pairs) {
  return "[\n" + pairs.map(([k, v]) => `        '${k}' => '${String(v).replace(/[\\']/g, "\\$&")}',`).join("\n") + "\n    ]";
}

/** Whitelists read by docs/contact.php and docs/apply.php. Labels are English because the email is read by staff. */
function enquiryOptionsPhp() {
  const topics = Object.values(content.enquiryTopics()).flat();
  const sizes = content.plm.businessSize.cards.map(([key, title]) => [key, title]);
  return `<?php
// Generated by improved-src/build.js. Do not edit: change improved-src/content and rebuild.
return [
    'types' => ${phpMap(content.enquiryTypes)},
    'topics' => ${phpMap(topics)},
    'needs' => ${phpMap(content.needs.map((n) => [n.key, n.title]))},
    'industries' => ${phpMap(content.industries.map((i) => [i.key, i.title]))},
    'sizes' => ${phpMap(sizes)},
    'jobs' => ${phpMap(content.jobs.map((j) => [j.slug, j.title]))},
    'langs' => ${phpArray(["en", "ja"])},
];
`;
}

function cell(text) {
  return String(text).replace(/\|/g, "\\|").replace(/\n/g, " ").replace(/\{\{br\}\}/g, " / ");
}

function pagesCell(pages) {
  const list = pages.map((p) => p.replace(/^ja\//, ""));
  if (!list.length) return "(not used)";
  if (list.length > 4) return `${list.slice(0, 3).join(", ")} and ${list.length - 3} more`;
  return list.join(", ");
}

function table(rows) {
  return ["| English | Japanese | Used on |", "| --- | --- | --- |"]
    .concat(rows.map((r) => `| ${cell(r.en)} | ${cell(r.ja)} | ${pagesCell(r.pages)} |`))
    .join("\n");
}

