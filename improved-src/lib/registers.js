/**
 * Generated records: the PHP whitelist for the contact form, the Japanese
 * translation register and the claim register. All three are rebuilt on every
 * build so that they cannot drift from the site.
 */
const content = require("../content");
const config = require("../config");
const jaQuotes = require("../i18n/ja-testimonials");

function phpArray(values) {
  return "[" + values.map((v) => `'${String(v).replace(/[\\']/g, "\\$&")}'`).join(", ") + "]";
}

function phpMap(pairs) {
  return "[\n" + pairs.map(([k, v]) => `        '${k}' => '${String(v).replace(/[\\']/g, "\\$&")}',`).join("\n") + "\n    ]";
}

/** Whitelists read by docs/contact.php and docs/apply.php. Labels are English because the email is read by staff. */
function enquiryOptionsPhp() {
  const topics = Object.values(content.enquiryTopics()).flat();
  const sizes = content.plm.businessSize.cards.map(([key, title]) => [key, title]);
  return `<?php
// Generated by improved-src/build.js. Do not edit: change improved-src/content and rebuild.
return [
    'types' => ${phpMap(content.enquiryTypes)},
    'topics' => ${phpMap(topics)},
    'needs' => ${phpMap(content.needs.map((n) => [n.key, n.title]))},
    'industries' => ${phpMap(content.industries.map((i) => [i.key, i.title]))},
    'sizes' => ${phpMap(sizes)},
    'jobs' => ${phpMap(content.jobs.map((j) => [j.slug, j.title]))},
    'langs' => ${phpArray(["en", "ja"])},
];
`;
}

function cell(text) {
  return String(text).replace(/\|/g, "\\|").replace(/\n/g, " ").replace(/\{\{br\}\}/g, " / ");
}

function pagesCell(pages) {
  const list = pages.map((p) => p.replace(/^ja\//, ""));
  if (!list.length) return "(not used)";
  if (list.length > 4) return `${list.slice(0, 3).join(", ")} and ${list.length - 3} more`;
  return list.join(", ");
}

function table(rows) {
  return ["| English | Japanese | Used on |", "| --- | --- | --- |"]
    .concat(rows.map((r) => `| ${cell(r.en)} | ${cell(r.ja)} | ${pagesCell(r.pages)} |`))
    .join("\n");
}

function japaneseRegister(i18n) {
  const all = i18n.register();
  const staging = all.filter((r) => r.source === "staging" && r.pages.length);
  const stagingUnused = all.filter((r) => r.source === "staging" && !r.pages.length);
  const fresh = all.filter((r) => r.source === "new");
  const areas = [...new Set(fresh.map((r) => r.area))];
  const quotes = content.testimonials.map((t) => ({ en: `${t.name}: “${t.quote}”`, ja: jaQuotes[t.name] || "", pages: ["index.html"] }));
  const out = [];
  out.push("# Japanese translation register");
  out.push("");
  out.push("Generated by `node improved-src/build.js`. Do not edit by hand: change the dictionaries in `improved-src/i18n/` and rebuild.");
  out.push("");
  out.push("Every Japanese string on the `/ja/` pages comes from one of two places:");
  out.push("");
  out.push(`- **Staging** (${staging.length} strings in use, plus the ${quotes.length} testimonial renderings): the Japanese text appears verbatim in the staging mirror (\`staging-original/\`). It was written or approved by whoever produced the staging site and is reused unchanged.`);
  out.push(`- **New** (${fresh.length} strings and ${i18n.patternCount} sentence patterns): written for this build by an AI system, not by a native-speaking professional translator. **None of it has had native review.** It should be read by a native Japanese speaker with PLM knowledge before launch.`);
  out.push("");
  out.push("The build does not hide gaps: it reports every English string on a Japanese page that has no entry. The current count is in the build output and in `notes/REVIEW.md`.");
  out.push("");
  out.push("## Decisions a reviewer should check first");
  out.push("");
  out.push("- **About Us** is 会社情報 and **Company Profile** is 会社概要. Staging used 会社概要 for both; they are different sections of the same page here, so the page name was changed. This is the only place where staging Japanese was overridden.");
  out.push("- **Siemens product names** (NX, Solid Edge, Capital, Teamcenter, Tecnomatix, Mendix) and the company name stay in Latin script.");
  out.push("- **Testimonials** show the original English as the authoritative text. The Japanese beneath each is the staging rendering, labelled 参考訳 (reference translation).");
  out.push("- **People's names and customer names** are not transliterated.");
  out.push("- **Job titles and job requirements** are translated; staging left them in English. Indian salary terms (CTC, LPA) are kept as abbreviations.");
  out.push("- **Register**: です・ます throughout, with polite request forms in forms and calls to action.");
  out.push("- **The privacy notice** (個人情報の取り扱い) also needs legal review; the Japanese is a translation of the English notice and has no independent legal standing.");
  out.push("");
  out.push("## Testimonials (staging Japanese, shown as reference translation)");
  out.push("");
  out.push(table(quotes));
  out.push("");
  out.push(`## Staging translations in use (${staging.length})`);
  out.push("");
  out.push(table(staging));
  for (const area of areas) {
    const rows = fresh.filter((r) => r.area === area);
    out.push("");
    out.push(`## New, awaiting native review: ${area} (${rows.length})`);
    out.push("");
    out.push(table(rows));
  }
  out.push("");
  out.push("## New sentence patterns");
  out.push("");
  out.push("These are built from parts by rule rather than stored as whole sentences:");
  out.push("");
  out.push("- Photo viewer labels: “Enlarge photo N of 12” → 写真を拡大（12枚中N枚目）");
  out.push("- Infographic labels: “Infographic: <industry>” → インフォグラフィック：<industry>");
  out.push("- Experience: “2+ Years” → 2年以上; “4 - 6 Years” → 4〜6年");
  out.push("- “Other roles in <discipline>” → 「<discipline>」のその他の職種");
  out.push("- “Careers that mention <product>” → <product>に関連する募集職種");
  out.push("- Job page descriptions: ThinkInnov-NexGenの募集職種：<title>（<location>、<experience>）。<summary>");
  out.push("- Page titles are translated part by part around the “|” separator.");
  out.push("");
  out.push(`## Staging translations not used by this build (${stagingUnused.length})`);
  out.push("");
  out.push("Kept in `improved-src/i18n/ja-staging.js` in case the English returns. The full staging dictionary, including filler that was deliberately not reused, is archived in `improved-src/i18n/staging-dictionary-archive.js`.");
  out.push("");
  return out.join("\n") + "\n";
}

